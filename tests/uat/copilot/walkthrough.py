"""Co-pilot: the settings card (provider, partner keys) and Ask PII answering with the records it used."""
import sys
from playwright.sync_api import sync_playwright, expect
OUT = sys.argv[1]; BASE = 'http://127.0.0.1:3100'; errors = []
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 1360, 'height': 1000}, extra_http_headers={'x-dev-user-email': 'sanjeev@uat.test'})
    ctx.add_init_script("try { localStorage.setItem('pii.page', 'settings') } catch (e) {}")
    page = ctx.new_page(); page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(f'{BASE}/app')
    adv = page.get_by_role('tab', name='Advanced')
    expect(adv).to_be_visible(timeout=20000)
    adv.click()
    card = page.get_by_role('region', name='AI co-pilot')
    expect(card).to_be_visible(timeout=20000)
    expect(card.get_by_label('AI provider (PII\'s key)').first).to_have_value('gemini')
    expect(card.get_by_role('status')).to_contain_text('Google Gemini, PII\'s key')
    card.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/1-copilot-settings.png')
    ctx.close()
    ctx = b.new_context(viewport={'width': 1360, 'height': 1000}, extra_http_headers={'x-dev-user-email': 'sanjeev@uat.test'})
    ctx.add_init_script("try { localStorage.setItem('pii.page', 'contacts') } catch (e) {}")
    page = ctx.new_page(); page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(f'{BASE}/app')
    page.get_by_role('button', name='Ask PII').click()
    d = page.get_by_role('dialog', name='Ask PII')
    d.get_by_role('textbox').fill('What do we have on Raj Singh?')
    d.get_by_role('button', name='Ask', exact=True).click()
    expect(d.get_by_text('From your records: Client Raj Singh', exact=False)).to_be_visible(timeout=15000)
    expect(d.get_by_role('region', name='Records used')).to_contain_text('[C1] Raj Singh')
    expect(d).to_contain_text('Answered by Google Gemini (PII\'s key)')
    page.screenshot(path=f'{OUT}/2-ask-pii.png')
    # The company rulebook: answers quote the section they came from.
    d.get_by_role('tab', name='Company rulebook').click()
    d.get_by_role('textbox').fill('What do I need before replacing a life policy?')
    d.get_by_role('button', name='Ask', exact=True).click()
    used = d.get_by_role('region', name='Passages quoted')
    expect(used).to_contain_text('PII Compliance Manual 2026', timeout=15000)
    expect(used).to_contain_text('Replacement of coverage')
    page.screenshot(path=f'{OUT}/3-ask-rulebook.png')
    ctx.close()
    # The rulebook in Settings.
    ctx = b.new_context(viewport={'width': 1360, 'height': 1000}, extra_http_headers={'x-dev-user-email': 'sanjeev@uat.test'})
    ctx.add_init_script("try { localStorage.setItem('pii.page', 'settings') } catch (e) {}")
    page = ctx.new_page(); page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(f'{BASE}/app')
    page.get_by_role('tab', name='Advanced').click()
    rb = page.get_by_role('region', name='Company rulebook')
    expect(rb).to_contain_text('PII Compliance Manual 2026', timeout=20000)
    rb.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/4-rulebook-settings.png')
    ctx.close()
    # A letter drafted on the deal from its signed records.
    ctx = b.new_context(viewport={'width': 1360, 'height': 1100}, extra_http_headers={'x-dev-user-email': 'sanjeev@uat.test'})
    ctx.add_init_script("try { localStorage.setItem('pii.page', 'pipelines') } catch (e) {}")
    page = ctx.new_page(); page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(f'{BASE}/app')
    page.get_by_text('Singh life review').first.click(timeout=20000)
    page.get_by_role('tab', name='Advice').click()
    lt = page.get_by_role('region', name='Letter drafts')
    lt.get_by_role('button', name='Draft it').click()
    expect(lt.get_by_label('Letter drafts')).to_have_value(__import__('re').compile('From your records'), timeout=15000)
    expect(lt).to_contain_text('Drawn from: [A1] Singh life review')
    lt.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/5-letter-draft.png')
    lt.get_by_role('button', name='Save to the deal').click()
    expect(lt.get_by_role('status')).to_contain_text('Saved to the deal as a note.')
    ctx.close()
    # The audit-ready score on the Compliance page.
    ctx = b.new_context(viewport={'width': 1360, 'height': 1000}, extra_http_headers={'x-dev-user-email': 'sanjeev@uat.test'})
    ctx.add_init_script("try { localStorage.setItem('pii.page', 'compliance') } catch (e) {}")
    page = ctx.new_page(); page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(f'{BASE}/app')
    ar = page.get_by_role('region', name='Audit-ready')
    expect(ar).to_contain_text('Singh life review', timeout=20000)
    expect(ar).to_contain_text('ID')
    ar.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/6-audit-ready.png')
    b.close()
print('copilot page errors:', errors); sys.exit(1 if errors else 0)
