"""Supervision: compliance writes a rule; the advisor is blocked, files the ID, asks for review; compliance approves; the deal moves."""
import sys
from playwright.sync_api import sync_playwright, expect
OUT = sys.argv[1]; BASE = 'http://127.0.0.1:3104'; errors = []
def ctx_for(b, who, page_name, h=1400):
    ctx = b.new_context(viewport={'width': 1360, 'height': h}, extra_http_headers={'x-dev-user-email': who})
    ctx.add_init_script(f"try {{ localStorage.setItem('pii.page', '{page_name}') }} catch (e) {{}}")
    page = ctx.new_page(); page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(f'{BASE}/app')
    return ctx, page
with sync_playwright() as p:
    b = p.chromium.launch()
    # 1. Compliance writes the rule.
    ctx, page = ctx_for(b, 'priya@uat.test', 'compliance', 1600)
    rp = page.get_by_role('region', name='Supervision rules')
    rp.get_by_role('button', name='New rule').click(timeout=20000)
    rp.get_by_label('Name').fill('Large life cases')
    rp.get_by_label('Risk').select_option('high')
    rp.get_by_label('Pipeline').select_option(label='Life')
    rp.get_by_label('Enters stage').select_option(label='Submitted')
    rp.get_by_label('Deal value at least ($)').fill('1000000')
    rp.get_by_text('Client ID record').click()
    rp.get_by_label('Review within (hours)').fill('24')
    rp.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/1-rule-form.png')
    rp.get_by_role('button', name='Save rule').click()
    expect(rp).to_contain_text('entering “Submitted”, in Life, deal value at least $1,000,000', timeout=10000)
    rp.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/2-rules.png')
    ctx.close()
    # 2. The advisor's move is blocked; the deal shows what the rule needs.
    ctx, page = ctx_for(b, 'sanjeev@uat.test', 'pipelines')
    page.get_by_text('Singh life review').first.click(timeout=20000)
    page.locator('#rec-stg').select_option(label='Submitted')
    expect(page.get_by_text('company rule “Large life cases”').first).to_be_visible(timeout=10000)
    page.screenshot(path=f'{OUT}/3-blocked.png')
    page.get_by_role('tab', name='ID & AML').click()
    docs = page.get_by_label('Documents seen (one per line)')
    docs.fill("Driver's licence (ON)")
    docs.locator('xpath=ancestor::form[1]').get_by_role('button', name='Save').click()
    expect(page.get_by_text("Driver's licence (ON)").first).to_be_visible(timeout=10000)
    page.get_by_role('tab', name='Files').click()
    card = page.get_by_role('region', name='Company rules for this deal')
    expect(card).to_contain_text('Paperwork on file', timeout=10000)
    card.get_by_label('Note for compliance (optional): Large life cases').fill('Client is a physician; income and net worth support the amount.')
    card.get_by_role('button', name='Ask compliance for a review').click()
    expect(card).to_contain_text('Review pending', timeout=10000)
    card.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/4-review-asked.png')
    ctx.close()
    # 3. Compliance approves from the queue.
    ctx, page = ctx_for(b, 'priya@uat.test', 'compliance', 1600)
    q = page.get_by_role('region', name='Reviews requested')
    expect(q).to_contain_text('Singh life review', timeout=20000)
    q.get_by_label('Your note (at least 10 characters): Singh life review').fill('Financials reviewed; amount is supported. Approved.')
    q.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/5-queue.png')
    q.get_by_role('button', name='Approve').click()
    expect(q).to_contain_text('Nothing waiting.', timeout=10000)
    ctx.close()
    # 4. The advisor moves the deal.
    ctx, page = ctx_for(b, 'sanjeev@uat.test', 'pipelines')
    page.get_by_text('Singh life review').first.click(timeout=20000)
    page.locator('#rec-stg').select_option(label='Submitted')
    page.wait_for_timeout(1500)
    page.get_by_role('tab', name='Files').click()
    expect(page.get_by_role('region', name='Company rules for this deal')).to_contain_text('Review approved', timeout=10000)
    b.close()
print('supervision page errors:', errors); sys.exit(1 if errors else 0)
