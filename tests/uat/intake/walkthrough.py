"""Client intake: the advisor makes a link; the client fills it in on a phone; the advisor reviews and applies it."""
import sys, re
from playwright.sync_api import sync_playwright, expect
OUT = sys.argv[1]; FILES = sys.argv[2]; BASE = 'http://127.0.0.1:3103'; errors = []
def open_deal(b):
    ctx = b.new_context(viewport={'width': 1360, 'height': 1500}, extra_http_headers={'x-dev-user-email': 'sanjeev@uat.test'})
    ctx.add_init_script("try { localStorage.setItem('pii.page', 'pipelines') } catch (e) {}")
    page = ctx.new_page(); page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(f'{BASE}/app')
    page.get_by_text('Singh life review').first.click(timeout=20000)
    return ctx, page
with sync_playwright() as p:
    b = p.chromium.launch()
    # 1. The advisor makes the link.
    ctx, page = open_deal(b)
    ic = page.get_by_role('region', name='Client intake')
    ic.get_by_role('button', name='Create the link').click()
    link = ic.get_by_label('Intake link')
    expect(link).to_have_value(re.compile(r'/intake/[A-Za-z0-9_-]{30,}$'))
    url = link.input_value()
    ic.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/1-advisor-link.png')
    ctx.close()
    # 2. The client fills it in on a phone-sized screen.
    cctx = b.new_context(viewport={'width': 400, 'height': 860}, locale='en-CA')
    cp = cctx.new_page(); cp.on('pageerror', lambda e: errors.append('client: ' + str(e)))
    cp.goto(url)
    expect(cp.get_by_role('heading', name='Hello Raj')).to_be_visible(timeout=20000)
    cp.get_by_label('Full legal name').fill('Raj Kumar Singh')
    cp.get_by_label('Date of birth').fill('1980-04-12')
    cp.get_by_label('Phone').fill('604-555-0199')
    cp.get_by_label('Occupation').fill('Civil engineer')
    cp.get_by_label('Marital status').select_option('married')
    cp.get_by_label('People who depend on you').fill('2')
    cp.get_by_label('Your yearly income ($)').fill('90000')
    cp.get_by_label('Mortgage owing ($)').fill('300000')
    cp.get_by_text('Replace income for the family').click()
    cp.get_by_text('Children’s education').click()
    cp.get_by_label('Monthly budget for insurance ($)').fill('150')
    cp.screenshot(path=f'{OUT}/2-client-form.png')
    cp.get_by_text('Collection and use of my personal information').click()
    cp.get_by_text('Receiving commercial electronic messages').click()
    cp.set_input_files('#file', f'{FILES}/policy-statement.pdf')
    expect(cp.get_by_text('Client upload - policy-statement.pdf')).to_be_visible(timeout=10000)
    cp.get_by_role('button', name='Send me a code').click()
    msg = cp.locator('#submit .msg')
    expect(msg).to_contain_text('test code', timeout=10000)
    code = re.search(r'(\d{6})', msg.inner_text()).group(1)
    cp.get_by_label('6-digit code').fill(code)
    cp.get_by_label('Type your full name').fill('Raj Kumar Singh')
    cp.get_by_text('My answers are true and complete').click()
    cp.locator('#submit').screenshot(path=f'{OUT}/3-client-submit.png')
    cp.get_by_role('button', name='Send to my advisor').click()
    expect(cp.get_by_text('Thank you. Your answers have been sent')).to_be_visible(timeout=10000)
    cctx.close()
    # 3. The advisor reviews and applies.
    ctx, page = open_deal(b)
    ic = page.get_by_role('region', name='Client intake')
    expect(ic).to_contain_text('Submitted: review it', timeout=20000)
    ic.get_by_role('button', name='Review').click()
    expect(ic).to_contain_text('Confirmed by the client as “Raj Kumar Singh”')
    expect(ic).to_contain_text('Date of birth: (empty) → 1980-04-12')
    ic.scroll_into_view_if_needed()
    page.screenshot(path=f'{OUT}/4-advisor-review.png')
    ic.get_by_role('button', name='Apply to the file').click()
    expect(ic.get_by_role('status').last).to_contain_text('a draft needs analysis is on the Advice tab', timeout=10000)
    page.get_by_role('tab', name='Advice').click()
    expect(page.get_by_text('Needs analysis (from the client\'s intake)').first).to_be_visible(timeout=10000)
    page.screenshot(path=f'{OUT}/5-needs-draft.png')
    b.close()
print('intake page errors:', errors); sys.exit(1 if errors else 0)
